numero= float(input("Digite seu número(considere o sinal de menos caso seja negativo ): ")) 

if numero >= 0: 
    print(f"\nSeu número digitado {numero} é POSITIVO\n") 
else: 
    print(f"\nSeu número digitado {numero} é NEGATIVO\n") 

